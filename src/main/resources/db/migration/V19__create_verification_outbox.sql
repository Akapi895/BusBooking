CREATE TABLE verification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    ciphertext BYTEA NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_until TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);
CREATE INDEX idx_verification_outbox_due
    ON verification_outbox (next_attempt_at, id) WHERE finished_at IS NULL;
CREATE INDEX idx_verification_outbox_user_created
    ON verification_outbox (user_id, created_at DESC);
